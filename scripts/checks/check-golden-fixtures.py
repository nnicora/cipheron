#!/usr/bin/env python3
"""cipheron's frozen wire fixtures are exactly what is committed — never regenerated, never added beside.

WHY THIS CHECK EXISTS
---------------------
spec/frozen/ (the frozen set: keysets, ciphertexts of every format, tenant key blobs, signatures, fingerprints,
digests and the signed and sealed transcripts, written once by cipheron's server, as manifest.json says) is what proves that a new build still reads what was written and still speaks the protocol a
deployed client speaks; the conformance kit is derived from it. Its whole value is that it is OLD. A fixture
regenerated by the code under test proves only that the code agrees with itself: a format change then passes its own
test. And a fixture that exists only in one working copy proves nothing in CI, where it is absent — the test that
reads it fails elsewhere, and nobody can tell which bytes the claim was made against.

WHAT IS ENFORCED
----------------
  * every fixture set in REQUIRED is committed: HEAD tracks at least one file under each;
  * nothing under the fixture paths (spec/frozen and any spec/frozen* beside it) differs from HEAD — modified, deleted, staged or
    not (`git diff --exit-code HEAD -- <paths>`);
  * nothing under the fixture paths is untracked, ignored files included: a new fixture is committed on
    its own, deliberately, not left beside the committed ones.

A failure says which files and what to do. The fixtures are changed only by a deliberate commit that
says so — never by a test run, a generator or a fix-up.

`self-test` proves each rule fires, in a throwaway repository.
"""

from __future__ import annotations

import os
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SPEC = "spec"

# git pathspecs: the frozen set and any set put beside it (spec/frozen-r3, a regenerated copy, ...): `*` matches
# across "/" in a plain pathspec, so spec/frozen* covers every file under them. spec/'s documents are not fixtures.
PATHSPECS = [f"{SPEC}/frozen*"]

# The fixture sets that must be in HEAD: the frozen set (one keyset version, ciphertext formats 3, 4, 5 and 6, the
# segmented object, encrypted JSON fields, the tenant key blob, the transcripts). Adding one here is part of the
# commit that adds it.
REQUIRED = [
    f"{SPEC}/frozen",
]


def git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True)


def problems(root: Path) -> list[str]:
    out: list[str] = []
    head = git(root, "rev-parse", "--verify", "--quiet", "HEAD^{commit}")
    if head.returncode != 0:
        return ["no HEAD commit: the fixtures cannot be compared with what is committed"]

    missing = []
    for path in REQUIRED:
        r = git(root, "ls-tree", "-r", "--name-only", "HEAD", "--", path)
        if r.returncode != 0:
            return [f"git ls-tree failed: {r.stderr.strip()}"]
        if not r.stdout.strip():
            missing.append(path)
    if missing:
        out.append(
            "not committed (HEAD tracks nothing under them):\n"
            + "".join(f"      {p}\n" for p in missing)
            + "    The frozen fixtures (and the generator that made them) are committed by the owner, in a\n"
            "    commit of their own, before any other change; until then this check fails by design.\n"
            "    Commit them as they are — do not regenerate them first:\n"
            f"      git add {' '.join(missing)}\n"
            "      git commit -m 'cipheron: commit the frozen wire fixtures'"
        )

    diff = git(root, "diff", "--name-status", "HEAD", "--", *PATHSPECS)
    if diff.returncode != 0:
        return out + [f"git diff failed: {diff.stderr.strip()}"]
    if diff.stdout.strip():
        out.append(
            "differ from HEAD (a fixture is never regenerated or edited in place):\n"
            + "".join(f"      {line}\n" for line in diff.stdout.strip().splitlines())
            + "    Restore them (`git checkout HEAD -- <path>`). If the format really changed, the change and the\n"
            "    fixtures written for it are committed by the owner in a commit of its own that says so (and\n"
            "    REQUIRED in scripts/checks/check-golden-fixtures.py names the set)."
        )

    others = git(root, "ls-files", "--others", "--", *PATHSPECS)
    if others.returncode != 0:
        return out + [f"git ls-files failed: {others.stderr.strip()}"]
    untracked = [p for p in others.stdout.splitlines() if p.strip()]
    if untracked:
        out.append(
            "untracked (ignored ones included), beside the committed fixtures:\n"
            + "".join(f"      {p}\n" for p in untracked)
            + "    A fixture that exists in one working copy proves nothing in CI. If these are the fixtures the\n"
            "    owner has not committed yet, commit them in a commit of their own; otherwise remove them."
        )
    return out


def report(root: Path) -> int:
    found = problems(root)
    if found:
        print(
            "check-golden-fixtures: cipheron's frozen fixtures are not exactly what is committed\n\n"
            + "\n\n".join(f"  {i}. {p}" for i, p in enumerate(found, 1)),
            file=sys.stderr,
        )
        return 1
    print("check-golden-fixtures: OK — " + ", ".join(p.removeprefix(SPEC + "/") for p in REQUIRED)
          + " are committed and unchanged; nothing untracked beside them")
    return 0


def self_test() -> int:
    failures = []
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        env = {**os.environ, "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t", "GIT_COMMITTER_NAME": "t",
               "GIT_COMMITTER_EMAIL": "t@t", "GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1"}

        def run(*args: str) -> None:
            subprocess.run(["git", "-C", str(root), *args], check=True, capture_output=True, env=env)

        def write(rel: str, text: str) -> None:
            p = root / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)

        def expect(name: str, want_substring: str | None) -> None:
            got = problems(root)
            text = "\n".join(got)
            if want_substring is None and got:
                failures.append(f"{name}: expected no problem, got {got}")
            elif want_substring is not None and want_substring not in text:
                failures.append(f"{name}: expected a problem containing {want_substring!r}, got {got}")

        run("init", "-q")
        write("README", "x")
        run("add", ".")
        run("commit", "-q", "-m", "base")
        # The required sets, and another set beside them (spec/frozen* is a fixture path).
        other_set = f"{SPEC}/frozen-other/manifest.json"
        required_files = [f"{path}/manifest.json" for path in REQUIRED]
        for path in required_files + [other_set]:
            write(path, "{}")
        expect("fixtures untracked", "not committed")
        expect("fixtures untracked (listed)", "untracked")
        run("add", ".")
        expect("fixtures staged, not committed", "not committed")
        run("commit", "-q", "-m", "fixtures")
        expect("fixtures committed and clean", None)
        write(other_set, '{"regenerated": true}')
        expect("a fixture beside the set modified", "differ from HEAD")
        run("checkout", "-q", "HEAD", "--", other_set)
        write(required_files[0], '{"regenerated": true}')
        expect("required fixture modified", "differ from HEAD")
        run("checkout", "-q", "HEAD", "--", required_files[0])
        (root / required_files[0]).unlink()
        expect("fixture deleted", "differ from HEAD")
        run("checkout", "-q", "HEAD", "--", required_files[0])
        write(f"{REQUIRED[0]}/extra.keyset.json", "{}")
        expect("new file beside the fixtures", "untracked")
        write(".gitignore", "*.keyset.json\n")
        expect("ignored file beside the fixtures", "extra.keyset.json")
        (root / f"{REQUIRED[0]}/extra.keyset.json").unlink()
        (root / ".gitignore").unlink()
        write(f"{SPEC}/frozen-r3/manifest.json", "{}")
        expect("a new set directory, untracked", "frozen-r3/manifest.json")
        (root / f"{SPEC}/frozen-r3/manifest.json").unlink()
        write(f"{SPEC}/frozen/sub/vectors.json", "{}")
        expect("a new file in a subdirectory of the set, untracked", "vectors.json")
        (root / f"{SPEC}/frozen/sub/vectors.json").unlink()
        write(f"{SPEC}/api.md", "edited")
        expect("a document in spec/ is not judged", None)

    if failures:
        print("check-golden-fixtures self-test FAILED:\n" + "\n".join(f"  - {f}" for f in failures), file=sys.stderr)
        return 1
    print("check-golden-fixtures self-test: OK — every rule fires (untracked, staged, modified, deleted, ignored, new set, "
          "new file)")
    return 0


if __name__ == "__main__":
    if sys.argv[1:] == ["self-test"]:
        sys.exit(self_test())
    if sys.argv[1:]:
        print("usage: check-golden-fixtures.py [self-test]", file=sys.stderr)
        sys.exit(2)
    sys.exit(report(REPO))
